import 'package:delegate_app/features/admin/domain/usecases/get_company_delegates.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:delegate_app/features/tasks/domain/entities/task_entity.dart';
import 'package:delegate_app/features/tasks/domain/usecases/create_task.dart';
import 'package:delegate_app/features/tasks/presentation/bloc/create_task_event.dart';
import 'package:delegate_app/features/tasks/presentation/bloc/create_task_state.dart';

class CreateTaskBloc extends Bloc<CreateTaskEvent, CreateTaskState> {
  final CreateTask createTask;
  final GetCompanyDelegates getCompanyDelegates;

  CreateTaskBloc({required this.createTask, required this.getCompanyDelegates})
    : super(const CreateTaskInitial()) {
    on<CreateTaskSubmitted>(_onCreateTask);
    on<LoadDelegatesRequested>(_onLoadDelegates);
  }

  Future<void> _onLoadDelegates(
    LoadDelegatesRequested event,
    Emitter<CreateTaskState> emit,
  ) async {
    emit(LoadingDelegates());
    final result = await getCompanyDelegates(
      GetCompanyDelegatesParams(
        organizationUID: event.organizationId,
        companyUID: event.companyId,
      ),
    );

    result.fold(
      (failure) => emit(CreateTaskError(message: failure.message)),
      (delegates) => emit(CreateTaskInitial(delegates: delegates)),
    );
  }

  Future<void> _onCreateTask(
    CreateTaskSubmitted event,
    Emitter<CreateTaskState> emit,
  ) async {
    final currentDelegates = state.delegates;
    emit(CreateTaskLoading(delegates: currentDelegates));

    final task = TaskEntity(
      uid: '', // Will be generated by Firestore
      title: event.title,
      description: event.description,
      priority: event.priority,
      status: TaskStatus.pending,
      assignedTo: event.assignedTo,
      assignedToName: event.assignedToName,
      companyId: event.companyId,
      createdBy: event.createdBy,
      createdByName: event.createdByName,
      dueDate: event.dueDate,
      createdAt: DateTime.now(),
    );

    final result = await createTask(event.organizationId, task);

    result.fold(
      (failure) => emit(
        CreateTaskError(message: failure.message, delegates: currentDelegates),
      ),
      (_) => emit(CreateTaskSuccess(delegates: currentDelegates)),
    );
  }
}
